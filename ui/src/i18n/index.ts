/**
 * 设置当前语言
 */
export function setLocale(locale: Locale): void {
  currentLocale = locale;
  // 保存到 localStorage
  try {
    localStorage.setItem("moltbot-locale", locale);
  } catch {
    // ignore
  }
  // 触发自定义事件通知语言变化
  window.dispatchEvent(new CustomEvent("moltbot-locale-change", { detail: { locale } }));
}

/**
 * 获取当前语言
 */
export function getLocale(): Locale {
  return currentLocale;
}

/**
 * 从 localStorage 或浏览器语言初始化
 */
export function initLocale(): void {
  try {
    const saved = localStorage.getItem("moltbot-locale") as Locale | null;
    if (saved && translations[saved]) {
      currentLocale = saved;
      return;
    }
  } catch {
    // ignore
  }

  // 检测浏览器语言
  const browserLang = navigator.language;
  if (browserLang.startsWith("zh")) {
    currentLocale = "zh-CN";
  } else {
    currentLocale = "en";
  }
}

/**
 * 获取翻译值，支持模板变量替换
 * 使用方式: t("key") 或 t("key", { var: "value" })
 */
export function t(key: string, vars?: Record<string, string> | string): string {
  const fallback = typeof vars === "string" ? vars : undefined;
  const variables = typeof vars === "object" ? vars : undefined;
  
  const keys = key.split(".");
  let value: unknown = translations[currentLocale];

  for (const k of keys) {
    if (value === null || typeof value !== "object") {
      return fallback ?? key;
    }
    value = (value as Record<string, unknown>)[k];
  }

  let result: string;
  if (typeof value === "string") {
    result = value;
  } else {
    result = fallback ?? key;
  }
  
  // 替换模板变量
  if (variables) {
    for (const [k, v] of Object.entries(variables)) {
      result = result.replace(new RegExp(`{{${k}}}`, "g"), v);
    }
  }
  
  return result;
}

/**
 * 模板翻译 - 支持变量替换（显式调用）
 * @deprecated 直接使用 t(key, vars) 即可
 */
export function tTemplate(key: string, vars: Record<string, string>): string {
  return t(key, vars);
}

